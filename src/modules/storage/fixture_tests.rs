//! Complete pinned definitions and independent literal Storage vectors.
use crate::modules::{
    board::{config::Limits, definition::Definition, offering::Board},
    services::schema::Support,
};
use sha2::{Digest, Sha256};

// Both offering directions bind the complete upstream contract, with only documented harness substitutions.
#[test]
fn complete_definition_matches_provided_and_wanted_offerings() {
    let offering: serde_json::Value =
        serde_json::from_str(include_str!("fixtures/offering.json")).unwrap();
    for field in ["providedServices", "wantedServices"] {
        let mut board = serde_json::json!({"version":1,"providedServices":[],"wantedServices":[]});
        board[field] = serde_json::json!([offering]);
        let board = Board::parse(&serde_json::to_vec(&board).unwrap(), Limits::default()).unwrap();
        let offering = &board.offerings["storage-standard"];
        let definition = Definition::parse(
            include_bytes!("fixtures/definition.json"),
            offering,
            Limits::default(),
        )
        .unwrap();
        assert_eq!(definition.support, Support::Known);
        let fields = definition.document.value()["input"]["fields"]
            .as_object()
            .unwrap();
        assert_eq!(fields.len(), 10);
        assert!(fields.contains_key("expectedExpiresAt"));
    }
}

// Literal upstream hash and prices are fixed evidence, not expected values generated by Storage helpers.
#[test]
fn literal_hash_and_price_vectors_remain_exact() {
    let digest = Sha256::digest(b"abc");
    let hex: String = digest.iter().map(|b| format!("{b:02x}")).collect();
    assert_eq!(
        hex,
        "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
    );
    let vectors: serde_json::Value =
        serde_json::from_str(include_str!("fixtures/prices.json")).unwrap();
    assert_eq!(
        vectors["store"],
        serde_json::json!([[1, 1, 1], [3, 10, 17]])
    );
    assert_eq!(vectors["retrieve"], serde_json::json!([[3, 2], [2, 1]]));
    assert_eq!(vectors["renew"], serde_json::json!([[3, 4, 6]]));
    assert_eq!(vectors["remove"], 2);
    assert_eq!(vectors["check"], 3);
}
