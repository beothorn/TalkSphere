//! Test-only entropy, lifecycle observation and literal upstream vector decoding.

use super::{error::CryptoError, ports::Entropy};
use std::{
    collections::VecDeque,
    sync::{
        Arc,
        atomic::{AtomicUsize, Ordering},
    },
};

pub struct ScriptedEntropy(pub VecDeque<Result<Vec<u8>, CryptoError>>);
impl Entropy for ScriptedEntropy {
    // Consume exactly one scripted request; exhaustion and size mismatch are failures.
    fn fill(&mut self, output: &mut [u8]) -> Result<(), CryptoError> {
        let bytes = self.0.pop_front().ok_or(CryptoError::Unavailable)??;
        if bytes.len() != output.len() {
            return Err(CryptoError::InvalidInput);
        }
        output.copy_from_slice(&bytes);
        Ok(())
    }
}

pub struct ReleaseProbe(pub Arc<AtomicUsize>);
impl Drop for ReleaseProbe {
    // Count capability releases without inspecting private memory after deallocation.
    fn drop(&mut self) {
        self.0.fetch_add(1, Ordering::SeqCst);
    }
}

// Decode literal hexadecimal fixture bytes, never values generated by production code.
pub fn hex(value: &str) -> Vec<u8> {
    let compact: String = value.chars().filter(|c| !c.is_whitespace()).collect();
    assert_eq!(compact.len() % 2, 0);
    (0..compact.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&compact[i..i + 2], 16).unwrap())
        .collect()
}

// Select one labeled value from the pinned envelope vector's independent literal bytes.
pub fn envelope(label: &str) -> Vec<u8> {
    let text = include_str!("fixtures/envelope.md");
    let tail = text
        .split(&format!("\n{label}:\n"))
        .nth(1)
        .expect("fixture label");
    hex(&tail
        .lines()
        .take_while(|line| !line.is_empty() && line.chars().all(|c| c.is_ascii_hexdigit()))
        .collect::<String>())
}

// Read exact Transport fixture bytes without computing signatures under test.
pub fn transport(label: &str) -> Vec<u8> {
    let text = include_str!("fixtures/transport.md");
    let tail = text
        .split(&format!("\n{label}:\n"))
        .nth(1)
        .expect("fixture label");
    hex(&tail
        .lines()
        .take_while(|line| !line.is_empty() && line.chars().all(|c| c.is_ascii_hexdigit()))
        .collect::<String>())
}

// Assemble untrusted public fixture fields without deriving expected cryptographic values.
pub fn recipient() -> super::api::RecipientCredential {
    super::credential::parse(
        &envelope("recipient CR2SE ID"),
        &envelope("recipient Ed25519 public key"),
        &envelope("recipient persistent X25519 public key"),
        &envelope("encryption-key binding signature"),
    )
    .unwrap()
}

// Supply exactly the pinned ephemeral private input and public nonce for one object.
pub fn object_entropy() -> ScriptedEntropy {
    ScriptedEntropy(VecDeque::from([
        Ok(envelope("raw ephemeral X25519 private-key input")),
        Ok(envelope("nonce")),
    ]))
}

// The deterministic source preserves call order and never invents missing entropy.
#[test]
fn entropy_script_rejects_exhaustion_sizes_and_dependency_failure() {
    let mut source = ScriptedEntropy(VecDeque::from([
        Ok(vec![1, 2]),
        Err(CryptoError::Unavailable),
        Ok(vec![3]),
    ]));
    let mut bytes = [0; 2];
    assert_eq!(source.fill(&mut bytes), Ok(()));
    assert_eq!(bytes, [1, 2]);
    assert_eq!(source.fill(&mut bytes), Err(CryptoError::Unavailable));
    assert_eq!(source.fill(&mut bytes), Err(CryptoError::InvalidInput));
    assert_eq!(source.fill(&mut bytes), Err(CryptoError::Unavailable));
}

// Release observation works on normal scope exit and vector parsing preserves fixed sizes.
#[test]
fn fixture_sizes_and_release_probe_are_independent() {
    let releases = Arc::new(AtomicUsize::new(0));
    {
        let _probe = ReleaseProbe(releases.clone());
    }
    assert_eq!(releases.load(Ordering::SeqCst), 1);
    assert_eq!(envelope("132-byte header").len(), 132);
    assert_eq!(envelope("sealed ciphertext plus tag (46 bytes)").len(), 46);
    assert_eq!(envelope("HKDF extract PRK").len(), 32);
    assert!(include_str!("fixtures/transport.md").contains("AUTH"));
}
